import { getAdministrativeUnitByCode } from "@/lib/geography/administrative-lookup";
import { formatAdministrativeAddress } from "@/lib/geography/normalize-address";
import type { DongNaiZone, ExperiencePackage, Farm, OcopStatus } from "@/types/naifarm";

function resolveUnitAddress(code: string, detailAddress: string) {
  const unit = getAdministrativeUnitByCode(code);
  const unitName = unit?.tenDayDu ?? "Phường Trấn Biên";
  return {
    administrativeUnitCode: code,
    administrativeUnitName: unitName,
    addressLabel: unit
      ? formatAdministrativeAddress(detailAddress, unit)
      : `${detailAddress}, ${unitName}, Thành phố Đồng Nai, Việt Nam`,
  };
}

function makeCoord(lat: number, lng: number) {
  return {
    lat,
    lng,
    latLabel: `${lat.toFixed(4)}°B`,
    lngLabel: `${lng.toFixed(4)}°Đ`,
    isDemoCoordinate: true as const,
    note: "Vị trí gần đúng theo vùng (chưa gắn ranh giới đa giác pháp lý).",
  };
}

function makeExtraFarm(cfg: {
  id: string;
  slug: string;
  name: string;
  ownerName: string;
  ownerAgeLabel: string;
  code: string;
  detail: string;
  zoneLabel: DongNaiZone;
  areaHa: number;
  mainCrops: string[];
  ocopStatus: OcopStatus;
  ocopLabel: string;
  ocopNote: string;
  growingZoneCode?: string;
  storyHeadline: string;
  storySummary: string;
  bannerImage: string;
  ownerPortrait: string;
  galleryImages: string[];
  youthSupporters: string[];
  lat: number;
  lng: number;
  expTitle?: string;
  expPrice?: number;
  expImage?: string;
}): Farm {
  const addr = resolveUnitAddress(cfg.code, cfg.detail);
  const experiences: ExperiencePackage[] = cfg.expTitle
    ? [
        {
          id: `exp-${cfg.id}`,
          farmId: cfg.id,
          title: cfg.expTitle,
          duration: "2,5 giờ (08:30 – 11:00)",
          pricePerGuest: cfg.expPrice ?? 70000,
          maxGuests: 14,
          scheduleSummary: "Thứ Bảy & Chủ Nhật (Đặt yêu cầu chờ nhà vườn xác nhận)",
          safetyNote: "Đi theo lối vườn có hướng dẫn viên thanh niên hỗ trợ; mang giày bít mũi.",
          image: cfg.expImage ?? cfg.bannerImage,
        },
      ]
    : [];

  return {
    id: cfg.id,
    slug: cfg.slug,
    name: cfg.name,
    ownerName: cfg.ownerName,
    ownerAgeLabel: cfg.ownerAgeLabel,
    administrativeUnitCode: addr.administrativeUnitCode,
    administrativeUnitName: addr.administrativeUnitName,
    zoneLabel: cfg.zoneLabel,
    region: addr.administrativeUnitName,
    detailAddress: cfg.detail,
    addressLabel: addr.addressLabel,
    areaHa: cfg.areaHa,
    mainCrops: cfg.mainCrops,
    ocopStatus: cfg.ocopStatus,
    ocopLabel: cfg.ocopLabel,
    ocopNote: cfg.ocopNote,
    growingZoneCode: cfg.growingZoneCode,
    storyHeadline: cfg.storyHeadline,
    storySummary: cfg.storySummary,
    bannerImage: cfg.bannerImage,
    ownerPortrait: cfg.ownerPortrait,
    galleryImages: cfg.galleryImages,
    youthSupporters: cfg.youthSupporters,
    coordinates: makeCoord(cfg.lat, cfg.lng),
    experiences,
    isDemo: true,
  };
}

